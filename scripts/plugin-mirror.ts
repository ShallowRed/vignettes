#!/usr/bin/env node
/**
 * Builds the tree published to `ShallowRed/vignettes-plugins`, the public
 * repository that installs the deck plugin for people who cannot read this one:
 * the marketplace reduced to the published plugins, the files of these plugins,
 * the license and `plugins/README.md` as its README. `node scripts/plugin-mirror.ts
 * <dir>` writes the tree in `<dir>`, which `.github/workflows/plugin-mirror.yml`
 * copies to that repository; `test/unit/plugin-mirror.test.ts` checks the tree.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

/** The published plugins, each with the only skills it may hold. */
export const PUBLISHED: Record<string, readonly string[]> = {
  'vignettes-decks': ['writing-decks'],
}

export const MARKETPLACE = '.claude-plugin/marketplace.json'

// The first line of a generated reference names the script of this repository
// that writes it.
const GENERATED_HEADER = /^<!-- Generated by scripts\/deck-plugin\.ts[^\n]*-->\n\n/

/** The files under a directory, by path from the repository root, without hidden files such as `.DS_Store`. */
export function filesUnder(root: string, dir: string): string[] {
  return readdirSync(join(root, dir), { recursive: true, withFileTypes: true })
    .filter(entry => entry.isFile() && !entry.name.startsWith('.'))
    .map(entry => relative(root, join(entry.parentPath, entry.name)))
    .sort()
}

/** The published tree, by path from its root. */
export function mirrorFiles(root: string): Record<string, string> {
  const read = (path: string) => readFileSync(join(root, path), 'utf8')
  const marketplace = JSON.parse(read(MARKETPLACE))
  marketplace.plugins = marketplace.plugins.filter((plugin: { name: string }) => Object.hasOwn(PUBLISHED, plugin.name))
  const files: Record<string, string> = {
    [MARKETPLACE]: `${JSON.stringify(marketplace, null, 2)}\n`,
    'LICENSE': read('LICENSE'),
    'README.md': read('plugins/README.md'),
  }
  for (const name of Object.keys(PUBLISHED)) {
    for (const path of filesUnder(root, `plugins/${name}`))
      files[path] = read(path).replace(GENERATED_HEADER, '')
  }
  return files
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = process.argv[2]
  if (!target) {
    console.error('Usage: node scripts/plugin-mirror.ts <dir>')
    process.exit(1)
  }
  const files = mirrorFiles(join(dirname(fileURLToPath(import.meta.url)), '..'))
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(target, path)), { recursive: true })
    writeFileSync(join(target, path), content)
  }
  console.log(`✓ ${Object.keys(files).length} file(s) written in ${target}`)
}
