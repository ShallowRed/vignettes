#!/usr/bin/env node
/**
 * Generates `packages/core/src/theme/tokens.generated.ts` from the manifests of the
 * application's own themes (`themes/`), so the runtime (frontmatter validation,
 * background images, deck dimensions, theme pickers) starts with the same
 * declarations the SCSS build compiles. Tenant themes from the content space are
 * not written here: the server registers them at runtime (see
 * `server/utils/themes.ts`), so the repository carries no tenant data.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { checkExtends, discoverThemes, manifestTokens, themeAliases } from '@vignettes/nuxt/build/theme-registry'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = join(root, 'packages/core/src/theme/tokens.generated.ts')

const all = discoverThemes(root)
for (const warning of [...themeAliases(all).warnings, ...checkExtends(all)])
  console.warn(`⚠ ${warning}`)

const app = all.filter(t => t.source === 'app')
const tokens = Object.fromEntries(app.map(t => [t.name, manifestTokens(t.manifest)]))
const { aliases } = themeAliases(app)

const content = `// AUTO-GENERATED by scripts/build-theme-tokens.ts from the manifests in themes/. Do not edit.
// Tenant themes (content space) are registered at runtime, not here.
import type { ThemeTokens } from './tokens.ts'

export const THEME_TOKENS: Record<string, ThemeTokens> = ${JSON.stringify(tokens, null, 2)}

/** Frontmatter names that resolve to another theme (declared by a theme's \`aliases\`). */
export const THEME_ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2)}
`

writeFileSync(outPath, content)
const tenant = all.filter(t => t.source === 'content').map(t => t.name)
console.log(`✓ ${app.length} application theme(s): ${app.map(t => t.name).join(', ')}${tenant.length ? `; ${tenant.length} tenant theme(s) left to runtime: ${tenant.join(', ')}` : ''}`)
