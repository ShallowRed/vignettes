#!/usr/bin/env node
/**
 * Generates `shared/theme/tokens.generated.ts` from the theme manifests, so the
 * runtime (frontmatter validation, background images, deck dimensions, theme
 * pickers) reads the same declarations the SCSS build compiles. Background paths
 * are turned into the public URLs the build copies the files to.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { checkExtends, discoverThemes, themeAliases, themeAssetUrl } from './lib/theme-registry.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = join(root, 'shared/theme/tokens.generated.ts')

const themes = discoverThemes(root)
const { aliases, warnings } = themeAliases(themes)
for (const warning of [...warnings, ...checkExtends(themes)])
  console.warn(`⚠ ${warning}`)

const tokens = Object.fromEntries(themes.map((theme) => {
  const { name, lang, parser, reveal, backgrounds } = theme.manifest
  const entry: Record<string, unknown> = { name }
  if (lang)
    entry.lang = lang
  if (parser)
    entry.parser = parser
  if (backgrounds) {
    entry.backgrounds = Object.fromEntries(
      Object.entries(backgrounds).map(([level, path]) => [level, themeAssetUrl(name, path)]),
    )
  }
  if (reveal)
    entry.reveal = reveal
  return [name, entry]
}))

const content = `// AUTO-GENERATED by scripts/build-theme-tokens.ts from the theme manifests. Do not edit.
// Themes found in themes/ and in the content space (\`NUXT_CONTENT_DIR/themes\`).
import type { ThemeTokens } from './tokens'

export const THEME_TOKENS: Record<string, ThemeTokens> = ${JSON.stringify(tokens, null, 2)}

/** Frontmatter names that resolve to another theme (declared by a theme's \`aliases\`). */
export const THEME_ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2)}
`

writeFileSync(outPath, content)
console.log(`✓ ${themes.length} theme(s): ${themes.map(t => t.name).join(', ')}`)
if (process.argv.includes('--check')) {
  // Reserved for a CI drift check; the file is committed and regenerated on every build.
}
