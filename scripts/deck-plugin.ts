#!/usr/bin/env node
/**
 * Writes the references of the deck authoring plugin (`plugins/vignettes-decks`)
 * from the code that parses and renders a deck: the frontmatter schema, the
 * annotations, the layouts and the components of `@vignettes/core` and of the
 * extension packages, and the READMEs of the packages that document them. The
 * plugin is installed in other projects, where this repository is out of reach,
 * so it carries its own copy; `test/unit/deck-plugin.test.ts` fails when the copy
 * drifts from its sources.
 */
import type { DeckComponent } from '@vignettes/core/deck'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { BUILT_IN_COMPONENTS, DECK_ANNOTATIONS, DECK_LAYOUTS, DeckMetaSchema } from '@vignettes/core/deck'
import { SCHEMA_COMPONENTS } from '@vignettes/schemas/components'
import { STORYBOOK_COMPONENTS } from '@vignettes/storybook/components'

export const SKILL_DIR = 'plugins/vignettes-decks/skills/writing-decks'

const GENERATED = '<!-- Generated by scripts/deck-plugin.ts: edit the source it names, then run `node scripts/deck-plugin.ts`. -->'

const COPIED_READMES: Record<string, string> = {
  'render-module.md': 'packages/nuxt/README.md',
  'explanation-kit.md': 'packages/schemas/README.md',
  'storybook.md': 'packages/storybook/README.md',
}

function frontmatterKeys(): string[] {
  return Object.entries(DeckMetaSchema.shape).map(([key, schema]) => {
    const inner = (schema as any).unwrap?.() ?? schema
    const options: unknown[] | undefined = inner.options
    const values = options?.every(value => typeof value === 'string') ? options as string[] : undefined
    return values ? `- \`${key}\`: ${values.map(v => `\`${v}\``).join(', ')}` : `- \`${key}\``
  })
}

function componentLines(components: readonly DeckComponent[]): string[] {
  return components.map((c) => {
    const aliases = c.aliases?.length ? `, also written ${c.aliases.map(a => `\`${a}\``).join(', ')}` : ''
    return `- \`${c.name}\`${aliases}${c.fullSlide ? '; takes the whole slide' : ''}`
  })
}

function formatReference(): string {
  return [
    GENERATED,
    '',
    '# Deck format',
    '',
    'The names a deck can use, read from the code that parses and renders it. The slide boundaries and the syntax of each component are in `render-module.md`, `explanation-kit.md` and `storybook.md`.',
    '',
    '## Frontmatter',
    '',
    'Validated against `DeckMetaSchema` of `@vignettes/core/deck`. An unknown key is kept and ignored; a malformed value is refused with the name of the key.',
    '',
    ...frontmatterKeys(),
    '',
    '## Annotations',
    '',
    'Written `:tag{…}` on a line of the slide. The parser reads them and removes them from the body.',
    '',
    ...DECK_ANNOTATIONS.map(a => `- \`:${a.tag}\`: ${a.description}`),
    '',
    '## Layouts',
    '',
    'Named by `:layout{name="…"}`.',
    '',
    ...DECK_LAYOUTS.map(l => `- \`${l.name}\`${l.fullSlide ? ': the whole slide in one block, without a header and body split' : ''}`),
    '',
    '## Components',
    '',
    'Written `::Name{…}` … `::` as a block, or `:Name{…}` inline.',
    '',
    '`@vignettes/nuxt`, shipped with every deck:',
    '',
    ...componentLines(BUILT_IN_COMPONENTS),
    '',
    '`@vignettes/schemas`, the explanation kit:',
    '',
    ...componentLines(SCHEMA_COMPONENTS),
    '',
    '`@vignettes/storybook`, live story embeds:',
    '',
    ...componentLines(STORYBOOK_COMPONENTS),
    '',
  ].join('\n')
}

/** The generated files of the plugin, by path from the repository root. */
export function deckPluginFiles(root: string): Record<string, string> {
  const files: Record<string, string> = { [`${SKILL_DIR}/references/format.md`]: formatReference() }
  for (const [name, source] of Object.entries(COPIED_READMES))
    files[`${SKILL_DIR}/references/${name}`] = `${GENERATED.replace('the source it names', `\`${source}\``)}\n\n${readFileSync(join(root, source), 'utf8')}`
  return files
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..')
  const files = deckPluginFiles(root)
  for (const [path, content] of Object.entries(files))
    writeFileSync(join(root, path), content)
  console.log(`✓ ${Object.keys(files).length} reference(s) written in ${SKILL_DIR}/references`)
}
