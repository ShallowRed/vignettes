import { readdirSync, readFileSync } from 'node:fs'
import { dirname, join, normalize } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { deckPluginFiles } from '../../scripts/deck-plugin.ts'
import { MARKETPLACE, mirrorFiles, PUBLISHED } from '../../scripts/plugin-mirror.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
// The directory of the published plugin that holds a path, if any.
const pluginOf = (path: string) => Object.keys(PUBLISHED).map(name => `plugins/${name}/`).find(dir => path.startsWith(dir))

// What a reader of the public repository cannot open: this private repository,
// the `@vignettes` packages, which npm does not publish, and the script that
// writes the references.
const PRIVATE_REFERENCES = [
  /ShallowRed\/vignettes(?![-\w])/,
  /npmjs\.com\/package\/@vignettes\//,
  /Generated by scripts\/deck-plugin\.ts/,
]

describe('tree published to the public plugin repository', () => {
  const tree = mirrorFiles(root)

  it('carries references that match their sources: run `node scripts/deck-plugin.ts` after changing them', () => {
    const references = Object.entries(deckPluginFiles(root)).filter(([path]) => pluginOf(path))
    expect(references.length).toBeGreaterThan(0)
    for (const [path, content] of references)
      expect(readFileSync(join(root, path), 'utf8'), path).toBe(content)
  })

  it('holds only the skills each published plugin may publish', () => {
    for (const [name, skills] of Object.entries(PUBLISHED))
      expect(readdirSync(join(root, `plugins/${name}/skills`), { withFileTypes: true }).filter(entry => entry.isDirectory()).map(entry => entry.name).sort(), name).toEqual([...skills].sort())
  })

  it('names nothing out of reach of a public reader', () => {
    for (const [path, content] of Object.entries(tree)) {
      for (const pattern of PRIVATE_REFERENCES)
        expect(content, `${path} matches ${pattern}`).not.toMatch(pattern)
    }
  })

  // A skill installed alone, as `gh skill install` does, keeps only the files
  // of its plugin.
  it('links only to files of the tree, and from a plugin only to files of that plugin', () => {
    for (const [path, content] of Object.entries(tree)) {
      for (const [, target] of content.matchAll(/\]\(\s*<?([^)\s>]+)/g)) {
        if (/^(?:[a-z]+:|#|\/)/.test(target))
          continue
        const linked = normalize(join(dirname(path), target.split('#')[0]))
        expect(tree, `${path} links to ${target}`).toHaveProperty([linked])
        expect(linked.startsWith(pluginOf(path) ?? ''), `${path} links out of its plugin to ${target}`).toBe(true)
      }
    }
  })

  it('lists each published plugin under the name of its manifest, at a source of the tree', () => {
    const { plugins } = JSON.parse(tree[MARKETPLACE])
    expect(plugins.map((plugin: { name: string }) => plugin.name).sort()).toEqual(Object.keys(PUBLISHED).sort())
    for (const plugin of plugins) {
      const manifest = join(normalize(plugin.source), '.claude-plugin/plugin.json')
      expect(tree, plugin.name).toHaveProperty([manifest])
      expect(JSON.parse(tree[manifest]).name).toBe(plugin.name)
    }
  })
})
